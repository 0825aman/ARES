"""reporter.py — Format evaluation benchmark outputs as JSON and Markdown."""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any


def generate_json_report(metrics_data: dict[str, Any]) -> str:
    """Format benchmark evaluation metrics as formatted JSON string."""
    payload = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "summary": metrics_data,
    }
    return json.dumps(payload, indent=2)


def generate_markdown_report(metrics_data: dict[str, Any]) -> str:
    """Format benchmark evaluation metrics as a GitHub Flavored Markdown table."""
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "# MAAR Evaluation & Benchmark Report",
        "",
        f"**Generated:** {now_str}  ",
        "",
        "## Summary Metrics",
        "",
        "| Metric Name | Value | Category |",
        "|:---|:---|:---|",
    ]

    for key, value in sorted(metrics_data.items()):
        category = "Structural"
        if "citation" in key or "evidence" in key or "section" in key or "duplicate" in key:
            category = "Quality"
        elif "approval" in key or "export" in key:
            category = "Workflow"

        val_str = f"{value:.2%}" if isinstance(value, float) and value <= 1.0 and "rate" in key else str(value)
        lines.append(f"| `{key}` | **{val_str}** | {category} |")

    lines.append("")
    lines.append("---")
    lines.append("*Generated by MAAR Evaluation Framework.*")
    return "\n".join(lines)
